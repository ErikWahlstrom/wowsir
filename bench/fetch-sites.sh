#!/bin/sh
# Fetch the W3C ARIA Authoring Practices examples at a pinned commit into bench/sites/.
# w3.org answers headless browsers with a Cloudflare check, so the benchmark serves
# these pages itself (bench.mjs starts a static server on 127.0.0.1:8982).
set -e
cd "$(dirname "$0")"
REPO=https://github.com/w3c/aria-practices.git
COMMIT=0f765e4dc33e966026114ac12a8380db1de3b787
mkdir -p sites/aria-practices && cd sites/aria-practices
[ -d .git ] || git init -q
git fetch -q --depth 1 "$REPO" "$COMMIT"
git checkout -q FETCH_HEAD
echo "aria-practices @ $(git rev-parse --short HEAD) → bench/sites/aria-practices"
# specLinks.mjs is generated by W3C's site build; without it every page logs an import error.
[ -f content/shared/js/specLinks.mjs ] || echo 'export const specLinks = () => () => {};' > content/shared/js/specLinks.mjs
